"""Pack the five special-mode illustration atlases without touching normal art.

Source PNGs are generated by the built-in image_gen tool. This script only
isolates grid cells, cleans almost transparent extraction haze and downsamples.
Run from app/: python scripts/prepare-special-card-art.py
"""
from pathlib import Path
import json
from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / '.local/card-art-source'
OUTPUT = ROOT / 'public/assets/cards'
THEMES = ('cats', 'seal', 'kuromi', 'adventure', 'minecraft')
CELL = 192


def source_cells(path):
    image = Image.open(path).convert('RGBA')
    if image.getchannel('A').getextrema()[0] != 0:
        raise ValueError(f'{path.name} must retain transparent source alpha')
    cells = []
    for index in range(8):
        column, row = index % 4, index // 4
        tile = image.crop((round(column * image.width / 4), round(row * image.height / 2),
                           round((column + 1) * image.width / 4), round((row + 1) * image.height / 2)))
        alpha = tile.getchannel('A')
        # Reject almost transparent extraction haze before finding connected art.
        solid = tile.copy()
        solid.putalpha(alpha.point(lambda value: 255 if value >= 112 else 0))
        # Deliberately keep disconnected paper cards, sparks and arrows: they
        # communicate each power and are intentional parts of the vignette.
        tile.putalpha(ImageChops.multiply(alpha, solid.getchannel('A').filter(ImageFilter.MaxFilter(5))))
        bounds = tile.getchannel('A').point(lambda value: 255 if value >= 64 else 0).getbbox()
        if not bounds:
            raise ValueError(f'Empty scene {path.name}/{index}')
        cells.append(tile.crop(bounds))
    return cells


def main():
    sizes = {}
    for theme in THEMES:
        atlas = Image.new('RGBA', (CELL * 4, CELL * 2))
        for index, original in enumerate(source_cells(SOURCES / f'special-{theme}.png')):
            original.thumbnail((CELL - 12, CELL - 12), Image.Resampling.LANCZOS)
            atlas.alpha_composite(original, ((index % 4) * CELL + (CELL - original.width) // 2,
                                              (index // 4) * CELL + (CELL - original.height) // 2))
        atlas.putalpha(atlas.getchannel('A').point(lambda value: 0 if value < 9 else round(value / 17) * 17))
        path = OUTPUT / f'{theme}-special.webp'
        atlas.save(path, 'WEBP', quality=82, method=6, exact=True)
        sizes[theme] = {'bytes': path.stat().st_size, 'width': atlas.width, 'height': atlas.height, 'cell': CELL, 'scenes': 8}
    print(json.dumps(sizes, indent=2))


if __name__ == '__main__':
    main()
